package util;

import java.util.Locale;

/** Integral conversions: %d %o %x %X %c with every flag, width and the extreme values. */
public class FormatInts {
    static void t(String f, Object... a) {
        try {
            System.out.println(f + " => [" + String.format(Locale.US, f, a) + "]");
        } catch (RuntimeException e) {
            System.out.println(f + " => " + e.getClass().getName() + ": " + e.getMessage());
        }
    }

    public static void main(String[] args) {
        t("%d", 0);
        t("%d", 42);
        t("%d", -42);
        t("%d", Integer.MAX_VALUE);
        t("%d", Integer.MIN_VALUE);
        t("%d", Long.MAX_VALUE);
        t("%d", Long.MIN_VALUE);
        t("%d", (byte) -128);
        t("%d", (short) -32768);
        t("%d", Byte.valueOf((byte) 5));
        t("%d", Short.valueOf((short) 5));
        t("%5d|", 42);
        t("%-5d|", 42);
        t("%5d|", -42);
        t("%-5d|", -42);
        t("%3d|", 12345);
        t("%05d", 42);
        t("%05d", -42);
        t("%08d", -1234567);
        t("%08d", 12345678);
        t("%+d", 42);
        t("%+d", -42);
        t("%+d", 0);
        t("% d", 42);
        t("% d", -42);
        t("% d", 0);
        t("%(d", 42);
        t("%(d", -42);
        t("%(d", 0);
        t("%+(d", 42);
        t("%+(d", -42);
        t("% (d", 42);
        t("% (d", -42);
        t("%,d", 999);
        t("%,d", 1000);
        t("%,d", -1000);
        t("%,d", 1234567);
        t("%,d", Long.MIN_VALUE);
        t("%,d", 0);
        t("%,8d|", 1234);
        t("%,-8d|", 1234);
        t("%,010d", 1234567);
        t("%,015d", -1234567);
        t("%+,d", 1234567);
        t("% ,d", 1234567);
        t("%(,d", -1234567);
        t("%(010d", -123);
        t("%(010d", 123);
        t("%+010d", 123);
        t("% 010d", 123);
        t("%010d", Integer.MIN_VALUE);
        t("%(015d", Long.MIN_VALUE);
        t("%+(12d|", -5);
        t("%-+8d|", 5);
        t("%-(8d|", -5);
        t("%- 8d|", 5);
        t("%d %d %d", 1, 2, 3);
        t("%2$d %1$d", 1, 2);
        t("%1$d %<d %<d", 7);
        t("%d", (Object) null);
        t("%5d|", (Object) null);
        t("%-5d|", (Object) null);
        t("%+d", (Object) null);
        t("%x", 255);
        t("%x", 0);
        t("%X", 255);
        t("%x", -1);
        t("%x", -1L);
        t("%x", (byte) -1);
        t("%x", (short) -1);
        t("%x", (byte) 0x7f);
        t("%X", 0xabcdefL);
        t("%X", -255L);
        t("%x", Integer.MIN_VALUE);
        t("%x", Long.MIN_VALUE);
        t("%x", Byte.MIN_VALUE);
        t("%x", (Object) null);
        t("%8x|", 255);
        t("%-8x|", 255);
        t("%08x", 255);
        t("%08X", 255);
        t("%010x|", -255);
        t("%#x", 255);
        t("%#X", 255);
        t("%#x", 0);
        t("%#x", -1);
        t("%#10x|", 255);
        t("%-#10x|", 255);
        t("%#010x|", 255);
        t("%#010X|", 255);
        t("%#010x|", -255);
        t("%#8x|", -255);
        t("%o", 8);
        t("%o", 0);
        t("%o", -1);
        t("%o", -1L);
        t("%o", (byte) -1);
        t("%o", (short) -1);
        t("%o", Integer.MIN_VALUE);
        t("%o", Long.MIN_VALUE);
        t("%#o", 8);
        t("%#o", 0);
        t("%#o", -8);
        t("%#o", Integer.MIN_VALUE);
        t("%10o|", 511);
        t("%-10o|", 511);
        t("%010o|", 511);
        t("%#10o|", 511);
        t("%#010o|", 511);
        t("%#010o|", -8);
        t("%c", 'a');
        t("%c", 65);
        t("%c", (byte) 66);
        t("%c", (short) 67);
        t("%c", 0x1F600);
        t("%c", 0x10FFFF);
        t("%5c|", 'a');
        t("%-5c|", 'a');
        t("%5c|", 0x1F600);
        t("%C", 'a');
        t("%C", 0x1F600);
        t("%c", Character.valueOf('x'));
        t("%c", Integer.valueOf(0x41));
        t("%c", (Object) null);
        t("%5c|", (Object) null);
        t("%d%%", 50);
        t("100%%");
        t("%5d%n", 7);
        t("%d", 'c');
        t("%d", true);
        t("%d", 1.5);
        t("%d", 1.5f);
        t("%d", "12");
        t("%x", 1.5);
        t("%o", "7");
        t("%x", 'x');
        t("%c", 1.5);
        t("%c", "s");
        t("%c", 5L);
        System.out.println("done");
    }
}
