package util;

import java.util.Locale;

/** The %e %f %g conversions: precision, rounding, flags, NaN, infinities, huge and tiny values. */
public class FormatFloats {
    static void t(String f, Object... a) {
        try {
            System.out.println(f + " => [" + String.format(Locale.US, f, a) + "]");
        } catch (RuntimeException e) {
            System.out.println(f + " => " + e.getClass().getName() + ": " + e.getMessage());
        }
    }

    public static void main(String[] args) {
        t("%f", 3.14159);
        t("%f", -3.14159);
        t("%f", 0.0);
        t("%f", -0.0);
        t("%f", 1.0);
        t("%f", 100.0);
        t("%f", 1e15);
        t("%f", 123456789.123456789);
        t("%f", 1.5e-5);
        t("%f", 1.0E-7);
        t("%f", 1e21);
        t("%f", 1e300);
        t("%f", Double.MAX_VALUE);
        t("%f", Double.MIN_VALUE);
        t("%f", Double.MIN_NORMAL);
        t("%.0f", 0.5);
        t("%.0f", 1.5);
        t("%.0f", 2.5);
        t("%.0f", 3.5);
        t("%.0f", 0.4);
        t("%.0f", 9.5);
        t("%.0f", 99.5);
        t("%.0f", 0.49999999999999994);
        t("%.1f", 0.05);
        t("%.1f", 0.15);
        t("%.1f", 0.25);
        t("%.1f", 0.35);
        t("%.1f", 0.45);
        t("%.1f", 9.95);
        t("%.1f", 99.95);
        t("%.1f", 0.95);
        t("%.2f", 1.005);
        t("%.2f", 2.675);
        t("%.2f", 0.125);
        t("%.2f", 0.375);
        t("%.2f", 1.115);
        t("%.3f", 0.0005);
        t("%.3f", 1234.5678);
        t("%.3f", 0.0);
        t("%.10f", 3.14159);
        t("%.20f", 0.1);
        t("%.20f", 1.0 / 3);
        t("%.17f", 0.5);
        t("%.30f", 1e-10);
        t("%.340f", Double.MIN_VALUE);
        t("%#.0f", 5.5);
        t("%#.0f", 0.4);
        t("%10.3f|", 1234.5678);
        t("%-10.3f|", 1234.5678);
        t("%10.3f|", -1234.5678);
        t("%+10.3f|", 1234.5678);
        t("% 10.3f|", 1234.5678);
        t("%(10.3f|", -1234.5678);
        t("%(.3f", 1234.5678);
        t("%010.2f|", -3.14159);
        t("%010.2f|", 3.14159);
        t("%+010.2f|", 3.14159);
        t("% 010.2f|", 3.14159);
        t("%(010.2f|", -3.14159);
        t("%08.3f|", 3.14159);
        t("%,f", 1234567.891);
        t("%,.2f", -1234567.891);
        t("%,.0f", 999999.5);
        t("%,.2f", 999.999);
        t("%,15.2f|", 1234567.891);
        t("%,015.2f|", 1234567.891);
        t("%e", 3.14159);
        t("%e", -31415.9);
        t("%e", 0.0);
        t("%e", -0.0);
        t("%e", 1e100);
        t("%e", 1e-100);
        t("%e", Double.MAX_VALUE);
        t("%e", Double.MIN_VALUE);
        t("%e", 9.9999995);
        t("%e", 9.9999994);
        t("%.0e", 5.5);
        t("%.0e", 6.5);
        t("%.0e", 0.0);
        t("%#.0e", 5.5);
        t("%#.0e", 0.0);
        t("%.2e", 9.995);
        t("%.3e", 1.0005);
        t("%.3e", 0.0);
        t("%.15e", 123456789.123456789);
        t("%.25e", 0.1);
        t("%E", 1234.5);
        t("%12.3e|", 3.14159);
        t("%-12.3e|", 3.14159);
        t("%012.3e|", -3.14159);
        t("%+.3e", 3.14159);
        t("%(.3e", -3.14159);
        t("%g", 3.14159);
        t("%g", 0.0);
        t("%g", -0.0);
        t("%g", 0.0001);
        t("%g", 0.00009999);
        t("%g", 0.00099999949);
        t("%g", 123456.0);
        t("%g", 1234567.0);
        t("%g", 999999.5);
        t("%g", 99999.95);
        t("%g", 100000.0);
        t("%g", 1e-5);
        t("%G", 1e-5);
        t("%G", 1e10);
        t("%.0g", 123.0);
        t("%.0g", 0.0);
        t("%.1g", 0.95);
        t("%.1g", 9.5);
        t("%.1g", 5e-5);
        t("%.1g", 5e-4);
        t("%.1g", 1e5);
        t("%.3g", 9.995);
        t("%.3g", 999.5);
        t("%.3g", 99.95);
        t("%.3g", 0.0001);
        t("%.3g", 1234.5);
        t("%.4g", 0.00012345);
        t("%.7g", 1234567.0);
        t("%.7g", 12345678.0);
        t("%.8g", 1e-4);
        t("%.10g", 1.0);
        t("%12g|", 3.0);
        t("%-12g|", 3.0);
        t("%012g|", -3.0);
        t("%+g", 3.0);
        t("% g", 3.0);
        t("%(g", -3.0);
        t("%,g", 123456.7);
        t("%,g", 1234567.891);
        t("%,.8g", 12345.0);
        t("%f", Double.NaN);
        t("%e", Double.NaN);
        t("%g", Double.NaN);
        t("%a", Double.NaN);
        t("%F", Double.NaN);
        t("%E", Double.NaN);
        t("%f", Double.POSITIVE_INFINITY);
        t("%f", Double.NEGATIVE_INFINITY);
        t("%E", Double.NEGATIVE_INFINITY);
        t("%10f|", Double.NaN);
        t("%-10f|", Double.POSITIVE_INFINITY);
        t("%010f|", Double.POSITIVE_INFINITY);
        t("%010f|", Double.NaN);
        t("%+f", Double.POSITIVE_INFINITY);
        t("%+f", Double.NaN);
        t("% f", Double.POSITIVE_INFINITY);
        t("%(f", Double.NEGATIVE_INFINITY);
        t("%(f", Double.POSITIVE_INFINITY);
        t("%(f", Double.NaN);
        t("%.2f", Float.valueOf(2.5f));
        t("%f", Float.valueOf(0.5f));
        t("%e", Float.valueOf(1.25f));
        t("%g", Float.valueOf(1.5f));
        t("%f", Float.valueOf(Float.NaN));
        t("%f", Float.valueOf(Float.POSITIVE_INFINITY));
        t("%f", (Object) null);
        t("%10.3f|", (Object) null);
        t("%e", (Object) null);
        t("%a", (Object) null);
        t("%f", 1);
        t("%f", 1L);
        t("%f", "1.5");
        t("%e", true);
        t("%g", 'a');
        System.out.println("done");
    }
}
