"""Generate the checked-in class file fixtures from their sources.

They are the classes and jar of the Rust unit tests (crates/classfile/tests/fixtures)
and tests/java/lazy/atomics/CraftedAtomics.class.

    python tools/fixtures.py          # rewrite the fixtures
    python tools/fixtures.py --check  # fail if they are out of date

javac's output depends on its version, so both modes need the JDK in JAVAC_MAJOR,
the one CI uses, and fail on any other: pick it with LAZYVM_JAVAC. A jar is compared
by its entries (name, date, method, contents), not its bytes, because its deflated
bytes depend on the zlib Python was built with.
"""

from __future__ import annotations

import io
import struct
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import javac  # noqa: E402
import lazyrt  # noqa: E402
from common import LAZYRT_CLASSES, ROOT, TESTS_SRC, die, find_tool  # noqa: E402

JAVAC_MAJOR = 25
FIXTURES = ROOT / "crates" / "classfile" / "tests" / "fixtures"
CRAFTED_SOURCE = ROOT / "tools" / "crafted" / "CraftedAtomics.java"
CRAFTED_TARGET = TESTS_SRC / "lazy" / "atomics" / "CraftedAtomics.class"
CRAFTED_CASTS = 12

# A continuation line in the manifest exercises the JAR spec's line folding.
MANIFEST = "Manifest-Version: 1.0\r\nMain-Class: app.VeryLongPackage\r\n Name.Main\r\n\r\n"


def require_javac() -> None:
    """Fail unless javac is the version that generates the fixtures."""
    done = subprocess.run([find_tool("LAZYVM_JAVAC", "javac"), "-version"], capture_output=True, text=True)
    version = (done.stdout + done.stderr).strip()
    if not version.startswith(f"javac {JAVAC_MAJOR}."):
        die(f"fixtures are generated by javac {JAVAC_MAJOR}, found '{version}': set LAZYVM_JAVAC")


def sample_jar(sample_class: bytes) -> bytes:
    """sample.jar: the manifest, Sample.class deflated and a stored text entry."""
    fixed = (1980, 1, 1, 0, 0, 0)
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w") as z:
        for name, data, method in [("META-INF/MANIFEST.MF", MANIFEST.encode(), zipfile.ZIP_DEFLATED),
                                   ("Sample.class", sample_class, zipfile.ZIP_DEFLATED),
                                   ("stored.txt", b"stored entry\n", zipfile.ZIP_STORED)]:
            info = zipfile.ZipInfo(name, fixed)
            info.compress_type = method
            z.writestr(info, data)
    return out.getvalue()


def read_pool(data: bytes) -> tuple[int, dict[int, str], dict[int, str]]:
    """Where the constant pool ends, its Utf8 entries and its class names, by index (JVMS 4.4)."""
    count = struct.unpack(">H", data[8:10])[0]
    at, index = 10, 1
    utf8: dict[int, str] = {}
    classes: dict[int, int] = {}
    while index < count:
        tag = data[at]
        if tag == 1:
            length = struct.unpack(">H", data[at + 1:at + 3])[0]
            utf8[index] = data[at + 3:at + 3 + length].decode("latin1")
            at += 3 + length
        elif tag == 7:
            classes[index] = struct.unpack(">H", data[at + 1:at + 3])[0]
            at += 3
        elif tag in (3, 4, 9, 10, 11, 12, 18):
            at += 5
        elif tag in (5, 6):
            at += 9
            index += 1
        elif tag in (8, 16):
            at += 3
        elif tag == 15:
            at += 4
        else:
            die(f"constant pool tag {tag}")
        index += 1
    return at, utf8, {i: utf8[name] for i, name in classes.items()}


def code_ranges(data: bytes, pool_end: int, utf8: dict[int, str]) -> list[range]:
    """The bytes of each method's `code` array (JVMS 4.1, 4.6, 4.7.3)."""
    def u2(i: int) -> int:
        return struct.unpack(">H", data[i:i + 2])[0]

    def u4(i: int) -> int:
        return struct.unpack(">I", data[i:i + 4])[0]

    ranges = []
    at = pool_end + 6
    at += 2 + 2 * u2(at)
    for is_method in (False, True):
        members = u2(at)
        at += 2
        for _ in range(members):
            attributes = u2(at + 6)
            at += 8
            for _ in range(attributes):
                if is_method and utf8[u2(at)] == "Code":
                    start = at + 14
                    ranges.append(range(start, start + u4(at + 10)))
                at += 6 + u4(at + 2)
    return ranges


def crafted_atomics() -> bytes:
    """A class that passes natives arguments javac and a verifier would refuse: its casts to
    Field and to array types are overwritten with `nop`. Its test runs with -Xverify:none.
    The scan does not decode instructions, so the exact count guards against a false match."""
    with tempfile.TemporaryDirectory() as out:
        javac.compile([CRAFTED_SOURCE], Path(out), bootclasspath=LAZYRT_CLASSES)
        data = bytearray((Path(out) / "lazy" / "atomics" / "CraftedAtomics.class").read_bytes())
    end, utf8, classes = read_pool(bytes(data))
    forged = {i for i, name in classes.items() if name == "java/lang/reflect/Field" or name.startswith("[")}
    patched = 0
    for code in code_ranges(bytes(data), end, utf8):
        for at in range(code.start, code.stop - 2):
            if data[at] == 0xC0 and (data[at + 1] << 8 | data[at + 2]) in forged:
                data[at:at + 3] = b"\0\0\0"
                patched += 1
    if patched != CRAFTED_CASTS:
        die(f"CraftedAtomics: removed {patched} casts, expected {CRAFTED_CASTS}")
    return bytes(data)


def generate() -> dict[Path, bytes]:
    """Every fixture, by the path it is checked in at."""
    lazyrt.build()
    files: dict[Path, bytes] = {}
    with tempfile.TemporaryDirectory() as out:
        javac.compile(sorted(FIXTURES.glob("*.java")), Path(out))
        for path in Path(out).glob("*.class"):
            files[FIXTURES / path.name] = path.read_bytes()
    files[FIXTURES / "sample.jar"] = sample_jar(files[FIXTURES / "Sample.class"])
    files[CRAFTED_TARGET] = crafted_atomics()
    return files


def jar_entries(data: bytes) -> list[tuple[str, tuple, int, bytes]]:
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        return [(i.filename, i.date_time, i.compress_type, z.read(i)) for i in z.infolist()]


def up_to_date(path: Path, wanted: bytes) -> bool:
    if not path.is_file():
        return False
    found = path.read_bytes()
    if path.suffix == ".jar":
        return jar_entries(found) == jar_entries(wanted)
    return found == wanted


def check(files: dict[Path, bytes]) -> None:
    stale = [path for path, data in files.items() if not up_to_date(path, data)]
    stale += [path for path in FIXTURES.glob("*.class") if path not in files]
    if stale:
        names = ", ".join(str(path.relative_to(ROOT)) for path in stale)
        die(f"out of date: {names}; run python tools/fixtures.py")
    print(f"fixtures: {len(files)} files up to date")


def main() -> None:
    require_javac()
    files = generate()
    if "--check" in sys.argv[1:]:
        check(files)
        return
    for path, data in files.items():
        path.write_bytes(data)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
