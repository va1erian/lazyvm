"""Generate java/lazyrt/src/java/lang/CaseMarks.java from the oracle JVM.

The Lithuanian and Turkic case rules of String.toLowerCase(Locale) and
toUpperCase(Locale) look at the combining marks around a letter. Which marks
count is not typed in: a small Java program asks the Java 8 oracle, and this
tool writes the answer out as a Java source file.

    python tools/case_marks.py           # dump and write the file
    python tools/case_marks.py --check   # compare the committed file with a fresh dump
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import golden  # noqa: E402
import javac  # noqa: E402
from common import BUILD, ROOT, die  # noqa: E402

WORK = BUILD / "case_marks"
DUMP_SRC = ROOT / "tools" / "case_marks" / "Dump.java"
OUT = ROOT / "java" / "lazyrt" / "src" / "java" / "lang" / "CaseMarks.java"

HEADER = """package java.lang;

/**
 * The mark sets behind the Lithuanian and Turkic case rules, as hex lo-hi
 * ranges. ABOVE: marks that sit above the base and end a search for a dot;
 * OTHER: marks a search skips; SOFT_DOTTED: letters whose dot above upper
 * case drops. Generated by tools/case_marks.py from the behaviour of the Java 8
 * oracle; do not edit.
 */
final class CaseMarks {
    private CaseMarks() {
    }
"""
NAMES = {"A": "ABOVE", "O": "OTHER", "S": "SOFT_DOTTED"}


def run_oracle() -> dict[str, str]:
    WORK.mkdir(parents=True, exist_ok=True)
    javac.compile([DUMP_SRC], WORK)
    java = golden.oracle(False)
    result = subprocess.run([java, "-cp", str(WORK), "Dump"], capture_output=True, text=True,
                            encoding="utf-8")
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        die("the dump program failed on the oracle")
    rows = {}
    for line in result.stdout.replace("\r\n", "\n").split("\n"):
        if line:
            key, ranges = line.split("\t", 1)
            rows[key] = ranges
    return rows


def literal(ranges: str) -> str:
    parts = [ranges[i:i + 100] for i in range(0, len(ranges), 100)]
    return "\n            + ".join(f'"{p}"' for p in parts)


def render(rows: dict[str, str]) -> str:
    fields = [f"    static final String {name} = {literal(rows[key])};" for key, name in NAMES.items()]
    return HEADER + "\n" + "\n\n".join(fields) + "\n}\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare the committed file only")
    args = parser.parse_args()
    text = render(run_oracle())
    if args.check:
        if OUT.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            die(f"{OUT.relative_to(ROOT)} differs from the oracle; run tools/case_marks.py")
        print("case_marks: CaseMarks.java matches the oracle")
    else:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
