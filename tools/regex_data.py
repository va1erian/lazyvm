"""Generate java/lazyrt/src/java/util/regex/UnicodeData.java from the oracle JVM.

The block and script tables behind \\p{InBlock} and \\p{IsScript} are not typed
in: a small Java program runs on the Java 8 oracle and prints, for every block
and script, its code point ranges and the names the oracle's forName accepts;
this tool writes them out as a Java source file.

    python tools/regex_data.py           # dump and write the file
    python tools/regex_data.py --check   # compare the committed file with a fresh dump
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import golden  # noqa: E402
import javac  # noqa: E402
from common import BUILD, ROOT, die  # noqa: E402

WORK = BUILD / "regex_data"
DUMP_SRC = ROOT / "tools" / "regex_data" / "Dump.java"
OUT = ROOT / "java" / "lazyrt" / "src" / "java" / "util" / "regex" / "UnicodeData.java"

HEADER = """package java.util.regex;

/**
 * Code point ranges of every Unicode block and script, as hex lo-hi pairs, with
 * the names each is accepted under. Generated by tools/regex_data.py from the
 * behaviour of Character.UnicodeBlock and Character.UnicodeScript on the Java 8
 * oracle; do not edit. Entry format: NAME|ALTERNATE|...:lo-hi,lo-hi.
 */
final class UnicodeData {
    private UnicodeData() {
    }
"""


def run_oracle() -> list[tuple[str, str, str]]:
    WORK.mkdir(parents=True, exist_ok=True)
    javac.compile([DUMP_SRC], WORK)
    java = golden.oracle(False)
    result = subprocess.run([java, "-cp", str(WORK), "Dump"], capture_output=True, text=True,
                            encoding="utf-8")
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        die("the dump program failed on the oracle")
    rows = []
    for line in result.stdout.replace("\r\n", "\n").split("\n"):
        if line:
            kind, names, ranges = (line.split("\t", 2) + [""])[:3]
            rows.append((kind, names, ranges))
    return rows


def literal(names: str, ranges: str) -> str:
    text = f"{names}:{ranges}"
    parts = [text[i:i + 100] for i in range(0, len(text), 100)]
    return "        " + "\n            + ".join(f'"{p}"' for p in parts) + ","


def render(rows: list[tuple[str, str, str]]) -> str:
    out = [HEADER, "    static final String[] SCRIPTS = {"]
    out += [literal(n, r) for k, n, r in rows if k == "S"]
    out += ["    };", "", "    static final String[] BLOCKS = {"]
    out += [literal(n, r) for k, n, r in rows if k == "B"]
    out += ["    };", "}", ""]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare the committed file only")
    args = parser.parse_args()
    text = render(run_oracle())
    if args.check:
        if OUT.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            die(f"{OUT.relative_to(ROOT)} differs from the oracle; run tools/regex_data.py")
        print("regex_data: UnicodeData.java matches the oracle")
    else:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
