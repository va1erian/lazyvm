"""Generate java/lazyrt/src/java/util/LocaleSymbolData.java from the oracle JVM.

Formatter writes numbers with the decimal and grouping characters of its locale.
Which locale uses which is not typed in: a small Java program asks the Java 8
oracle for every locale it has symbols for, and this tool writes the answer
out as a compact string that LocaleSymbols reads. Locales whose digits are not
0-9 (hi_IN) are left out and print as in the default locale.

    python tools/locale_symbols.py           # dump and write the file
    python tools/locale_symbols.py --check   # compare the committed file with a fresh dump
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import golden  # noqa: E402
import javac  # noqa: E402
from common import BUILD, ROOT, die  # noqa: E402

WORK = BUILD / "locale_symbols"
DUMP_SRC = ROOT / "tools" / "locale_symbols" / "Dump.java"
OUT = ROOT / "java" / "lazyrt" / "src" / "java" / "util" / "LocaleSymbolData.java"
DEFAULT = (".", ",")

HEADER = """package java.util;

/**
 * Decimal and grouping characters per locale: groups separated by ';', each group
 * its two characters (decimal, grouping) and then ",key," for every language,
 * language_COUNTRY or language_COUNTRY_#Script it applies to. A locale not listed uses its language's entry,
 * and a language not listed uses '.' and ','. Generated by tools/locale_symbols.py
 * from the behaviour of the Java 8 oracle; do not edit.
 */
final class LocaleSymbolData {
    private LocaleSymbolData() {
    }

"""


def run_oracle() -> dict[str, tuple[str, str]]:
    WORK.mkdir(parents=True, exist_ok=True)
    javac.compile([DUMP_SRC], WORK)
    java = golden.oracle(False)
    result = subprocess.run([java, "-Duser.language=en", "-cp", str(WORK), "Dump"],
                            capture_output=True, text=True, encoding="utf-8")
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        die("the dump program failed on the oracle")
    rows = {}
    for line in result.stdout.replace("\r\n", "\n").split("\n"):
        parts = line.split("\t")
        if len(parts) == 3:
            rows[parts[0]] = (chr(int(parts[1], 16)), chr(int(parts[2], 16)))
    return rows


def entries(rows: dict[str, tuple[str, str]]) -> dict[tuple[str, str], list[str]]:
    """Keep a locale only where it differs from what a lookup would find without it.

    A script entry is always kept: the lookup for a script must stop there, even when it
    says the same as the default (sr in Latin script has the root's symbols).
    """
    groups: dict[tuple[str, str], list[str]] = {}
    for key in sorted(rows):
        parent = rows.get(key.split("_")[0], DEFAULT) if "_" in key else DEFAULT
        if rows[key] != parent or "#" in key:
            groups.setdefault(rows[key], []).append(key)
    return groups


def escape(c: str) -> str:
    return "\\u%04x" % ord(c) if ord(c) > 126 or c in "\"\\" else c


def render(rows: dict[str, tuple[str, str]]) -> str:
    groups = entries(rows)
    parts = [escape(d) + escape(g) + "," + ",".join(keys) + "," for (d, g), keys in sorted(groups.items())]
    chunks = [";".join(parts)[i:i + 90] for i in range(0, len(";".join(parts)), 90)]
    text = '"' + '"\n            + "'.join(chunks) + '"'
    return HEADER + f"    static final String DATA = {text};\n}}\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare the committed file only")
    args = parser.parse_args()
    text = render(run_oracle())
    if args.check:
        if OUT.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            die(f"{OUT.relative_to(ROOT)} differs from the oracle; run tools/locale_symbols.py")
        print("locale_symbols: LocaleSymbolData.java matches the oracle")
    else:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
